def _result(message_id: Any, result: dict[str, Any]) -> dict[str, Any]:
    return {"jsonrpc": "2.0", "id": message_id, "result": result}


def _error(message_id: Any, code: int, message: str) -> dict[str, Any]:
    return {"jsonrpc": "2.0", "id": message_id, "error": {"code": code, "message": message}}


class McpServer:
    def __init__(self, config: ServerConfig):
        self.config = config
        self.initialize_seen = False
        self.initialized = False

    def handle(self, message: Any) -> dict[str, Any] | None:
        if not isinstance(message, dict):
            return _error(None, -32600, "Invalid Request: expected a JSON object.")
        message_id = message.get("id")
        is_notification = "id" not in message
        if message.get("jsonrpc") != "2.0" or not isinstance(message.get("method"), str):
            return None if is_notification else _error(message_id, -32600, "Invalid Request.")
        params = message.get("params", {})
        if not isinstance(params, dict):
            return None if is_notification else _error(message_id, -32602, "Invalid params: expected an object.")

        method = message["method"]
        if method == "initialize":
            if is_notification:
                return None
            requested = params.get("protocolVersion")
            if not isinstance(requested, str):
                return _error(message_id, -32602, "Invalid params: protocolVersion is required.")
            negotiated = requested if requested in SUPPORTED_PROTOCOL_VERSIONS else LATEST_PROTOCOL_VERSION
            self.initialize_seen = True
            return _result(
                message_id,
                {
                    "protocolVersion": negotiated,
                    "capabilities": {"tools": {"listChanged": False}},
                    "serverInfo": {"name": SERVER_NAME, "version": SERVER_VERSION},
                    "instructions": SERVER_INSTRUCTIONS,
                },
            )
        if method == "notifications/initialized":
            if self.initialize_seen:
                self.initialized = True
            return None
        if method in {"notifications/cancelled", "notifications/roots/list_changed"}:
            return None
        if method == "ping":
            return None if is_notification else _result(message_id, {})
        if not self.initialized:
            return None if is_notification else _error(message_id, -32002, "Server not initialized.")
        if method == "tools/list":
            return None if is_notification else _result(message_id, {"tools": TOOLS})
        if method == "tools/call":
            if is_notification:
                return None
            name = params.get("name")
            arguments = params.get("arguments", {})
            if not isinstance(name, str) or not isinstance(arguments, dict):
                return _error(message_id, -32602, "Invalid params for tools/call.")
            try:
                data = tool_call(name, arguments, self.config)
                return _result(message_id, _tool_result(data))
            except ToolInputError as exc:
                return _result(message_id, _tool_result({"ok": False, "error": str(exc)}, is_error=True))
            except Exception:  # Keep private paths and implementation details out of client-visible errors.
                return _result(
                    message_id,
                    _tool_result({"ok": False, "error": "Internal QA MCP tool error."}, is_error=True),
                )
        return None if is_notification else _error(message_id, -32601, "Method not found.")


def _send(message: dict[str, Any]) -> None:
    sys.stdout.write(json.dumps(message, ensure_ascii=False, separators=(",", ":")) + "\n")
    sys.stdout.flush()


def serve_stdio(config: ServerConfig) -> int:
    try:
        sys.stdin.reconfigure(encoding="utf-8")
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")
    except AttributeError:
        pass
    server = McpServer(config)
    while True:
        raw_line = sys.stdin.readline(MAX_REQUEST_CHARS + 1)
        if not raw_line:
            break
        if len(raw_line) > MAX_REQUEST_CHARS:
            while raw_line and not raw_line.endswith("\n"):
                raw_line = sys.stdin.readline(MAX_REQUEST_CHARS + 1)
            _send(_error(None, -32700, "Parse error: request is too large."))
            continue
        line = raw_line.strip()
        if not line:
            continue
        try:
            message = json.loads(line)
        except json.JSONDecodeError:
            _send(_error(None, -32700, "Parse error."))
            continue
        response = server.handle(message)
        if response is not None:
            _send(response)
    return 0


def _emit(data: dict[str, Any]) -> None:
    print(json.dumps(data, ensure_ascii=False, indent=2))


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Read-only Codex QA Memory MCP server")
    parser.add_argument("--version", action="version", version=f"%(prog)s {SERVER_VERSION}")
    parser.add_argument("--memory-root", help="Override QA memory root for this server process.")
    parser.add_argument("--diary-root", help="Override QA diary root for this server process.")
    subparsers = parser.add_subparsers(dest="command")
    subparsers.add_parser("serve", help="Run the stdio MCP server (default).")
    subparsers.add_parser("health", help="Run a one-time read-only health check.")

    recall = subparsers.add_parser("recall", help="Run a one-time structured memory recall.")
    recall.add_argument("--query", default="")
    recall.add_argument("--mode", choices=sorted(MODE_BUDGETS), default="quick")
    recall.add_argument("--include-candidates", action="store_true")
    recall.add_argument("--project-hint", default="")

    diary = subparsers.add_parser("diary-search", help="Run a one-time QA diary evidence search.")
    diary.add_argument("--query", default="")
    diary.add_argument("--source-ref", default="")
    diary.add_argument("--date", default="")
    diary.add_argument("--session-id", default="")
    diary.add_argument("--thread-id", default="")
    diary.add_argument("--limit", type=int, default=8)
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    config = config_from_environment(args.memory_root, args.diary_root)
    if args.command in (None, "serve"):
        return serve_stdio(config)
    try:
        if args.command == "health":
            _emit(qa_memory_health(config))
            return 0
        if args.command == "recall":
            payload: dict[str, Any] = {
                "query": args.query,
                "mode": args.mode,
                "include_candidates": args.include_candidates,
                "project_hint": args.project_hint,
            }
            _emit(qa_memory_recall(payload, config))
            return 0
        if args.command == "diary-search":
            _emit(
                qa_diary_search(
                    {
                        "query": args.query,
                        "source_ref": args.source_ref,
                        "date": args.date,
                        "session_id": args.session_id,
                        "thread_id": args.thread_id,
                        "limit": args.limit,
                    },
                    config,
                )
            )
            return 0
    except ToolInputError as exc:
        _emit({"ok": False, "error": str(exc)})
        return 2
    parser.error("unknown command")
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
